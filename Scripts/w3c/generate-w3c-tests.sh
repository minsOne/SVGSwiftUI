    manifest = json.load(handle)

fixtures = manifest.get("fixtures", [])


def normalize_mode(value: str) -> str:
    normalized = str(value or "parse").lower()
    if normalized not in {"parse", "render"}:
        return "parse"
    return normalized


def normalize_expected(value: str) -> str:
    normalized = str(value or "pass").lower()
    if normalized not in {"pass", "fail", "unsupported"}:
        return "unsupported"
    return normalized


def normalize_unsupported_features(value: object) -> list[str]:
    if not isinstance(value, list):
        return []
    output: list[str] = []
    for item in value:
        text = str(item).strip()
        if text:
            output.append(text)
    return output


def quote(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f"\"{escaped}\""


def quote_string_list(values: list[str]) -> str:
    items = ", ".join(quote(value) for value in values)
    return f"[{items}]"


