#!/usr/bin/env bash
set -euo pipefail

MANIFEST=${1:-}
OUTPUT=${2:-}

if [[ -z "$MANIFEST" || -z "$OUTPUT" ]]; then
  cat <<USAGE
Usage: ./Scripts/w3c/generate-w3c-tests.sh <manifest-path> <output-path>

Examples:
  ./Scripts/w3c/generate-w3c-tests.sh Tests/SVGSwiftUITests/W3C/w3c-manifest.json Tests/SVGSwiftUITests/W3CGeneratedTests.swift
USAGE
  exit 1
fi

if [[ ! -f "$MANIFEST" ]]; then
  echo "Manifest file not found: $MANIFEST" >&2
  exit 1
fi

if ! command -v python3 >/dev/null 2>&1; then
  echo "python3 is required by this generator." >&2
  exit 1
fi

mkdir -p "$(dirname "$OUTPUT")"

python3 - "$MANIFEST" "$OUTPUT" <<'PY'
